/**
 * HAP-1820: bind mounts in infrastructure/docker/docker-compose.yml must be mountable.
 *
 * 1. Every relative bind-mount source must resolve to an existing path in the repo.
 *    Grafana's provisioning mounts used `../../monitoring/...` (-> <repo>/monitoring, which
 *    does not exist). Docker silently bind-mounts an empty auto-created directory for a
 *    missing source, so Grafana booted with no datasource and no dashboards. Compose
 *    resolves relative sources against the compose file's directory; this does the same.
 *
 * 2. No mount target may sit under another mount's target when that parent is read-only,
 *    unless the nested mountpoint already exists inside the parent's source directory.
 *    runc must mkdir the nested mountpoint inside the parent; on a `:ro` bind mount that
 *    fails with `mkdirat ...: read-only file system` and the container never starts
 *    (Grafana: dashboards JSON mounted at /etc/grafana/provisioning/dashboards/cmdb,
 *    nested in the :ro provisioning/dashboards mount).
 */
import { existsSync, readFileSync } from 'fs';
import { dirname, posix, resolve } from 'path';
import { parse } from 'yaml';

const REPO = resolve(__dirname, '../../..');
const COMPOSE_FILE = resolve(REPO, 'infrastructure/docker/docker-compose.yml');
const COMPOSE_DIR = dirname(COMPOSE_FILE);

// TLS material is generated by the operator's certificate tooling before `up`, so it is
// absent in a clean checkout by design: `.gitignore` ignores `infrastructure/docker/ssl/`
// (keeping only generate-self-signed-certs.sh and .gitkeep), and
// infrastructure/docker/SSL_CERTIFICATE_SETUP.md documents generating it.
const GENERATED_AT_DEPLOY = new Set([
  'infrastructure/docker/ssl/neo4j',
  'infrastructure/docker/ssl/postgres',
  'infrastructure/docker/ssl/redis',
]);

type Node = Record<string, unknown>;
type Mount = {
  service: string;
  /** Raw source as written (named volume, interpolated path, or relative/absolute path). */
  source: string | null;
  /** Container path, normalised. */
  target: string;
  readOnly: boolean;
  /** Absolute host path for relative bind mounts; null otherwise. */
  resolved: string | null;
};

const isMap = (value: unknown): value is Node =>
  typeof value === 'object' && value !== null && !Array.isArray(value);

// Split a short-syntax volume entry on `:` outside `${...}` (interpolation defaults such as
// `${BACKUP_DIR:-/var/backups}` contain colons).
function splitShort(entry: string): string[] {
  const parts: string[] = [];
  let depth = 0;
  let current = '';
  for (let i = 0; i < entry.length; i++) {
    const ch = entry[i];
    if (ch === '$' && entry[i + 1] === '{') depth++;
    else if (ch === '}' && depth > 0) depth--;
    if (ch === ':' && depth === 0) {
      parts.push(current);
      current = '';
    } else {
      current += ch;
    }
  }
  parts.push(current);
  return parts;
}

function parseMount(service: string, entry: unknown): Mount | null {
  let source: string | null = null;
  let target: string;
  let readOnly = false;
  let isBind = false;

  if (typeof entry === 'string') {
    const parts = splitShort(entry);
    if (parts.length < 2) return null; // anonymous volume: no host source, no nesting parent
    source = parts[0];
    target = parts[1];
    readOnly = (parts[2] ?? '').split(',').includes('ro');
    isBind = source.startsWith('.');
  } else if (isMap(entry) && typeof entry.target === 'string') {
    source = typeof entry.source === 'string' ? entry.source : null;
    target = entry.target;
    readOnly = entry.read_only === true;
    isBind = entry.type === 'bind' && source !== null && source.startsWith('.');
  } else {
    return null;
  }

  return {
    service,
    source,
    target: posix.normalize(target),
    readOnly,
    resolved: isBind && source !== null ? resolve(COMPOSE_DIR, source) : null,
  };
}

function allMounts(): Mount[] {
  const compose = parse(readFileSync(COMPOSE_FILE, 'utf8')) as Node;
  const services = compose.services;
  if (!isMap(services)) throw new Error('docker-compose.yml has no services map');

  const mounts: Mount[] = [];
  for (const [service, definition] of Object.entries(services)) {
    const volumes = isMap(definition) ? definition.volumes : undefined;
    if (!Array.isArray(volumes)) continue;
    for (const entry of volumes) {
      const mount = parseMount(service, entry);
      if (mount !== null) mounts.push(mount);
    }
  }
  return mounts;
}

const repoRelative = (absolute: string): string => absolute.slice(REPO.length + 1);

describe('docker-compose bind mounts', () => {
  const mounts = allMounts();
  const relativeBinds = mounts.filter((m) => m.resolved !== null);

  it('Grafana provisioning mounts resolve to existing paths', () => {
    const grafana = relativeBinds.filter((m) => m.service === 'grafana');
    expect(grafana.length).toBeGreaterThanOrEqual(3);
    const missing = grafana.filter((m) => !existsSync(m.resolved as string)).map((m) => m.source);
    expect(missing).toEqual([]);
  });

  it('every service relative bind-mount source exists (except deploy-time TLS material)', () => {
    const missing = relativeBinds
      .filter((m) => !GENERATED_AT_DEPLOY.has(repoRelative(m.resolved as string)))
      .filter((m) => !existsSync(m.resolved as string))
      .map((m) => `${m.service}: ${m.source} -> ${repoRelative(m.resolved as string)}`);
    expect(missing).toEqual([]);
  });

  it('no mount target is nested under a read-only mount unless the mountpoint already exists', () => {
    const offenders: string[] = [];
    for (const child of mounts) {
      for (const parent of mounts) {
        if (parent === child || parent.service !== child.service || !parent.readOnly) continue;
        if (!child.target.startsWith(`${parent.target}/`)) continue;
        const inside = child.target.slice(parent.target.length + 1);
        // Only a bind-mount parent has a host directory in which the mountpoint can pre-exist.
        const prepared = parent.resolved !== null && existsSync(resolve(parent.resolved, inside));
        if (!prepared) {
          offenders.push(
            `${child.service}: ${child.target} is nested in read-only mount ${parent.target}`
          );
        }
      }
    }
    expect(offenders).toEqual([]);
  });
});
